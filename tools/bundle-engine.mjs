/**
 * Concatenates src/legacy/*.js into public/js/tncsc-engine.js.
 *
 * Why a bundle instead of 18 <script> tags: the engine was authored as one
 * contiguous script, so it relies on `var`/function hoisting across the whole
 * block - the Daily Entry init IIFE reads `currentUser`, which is only declared
 * hundreds of lines further down in the auth section. Split across separate
 * classic scripts that becomes a ReferenceError; concatenated back into one, it
 * behaves exactly as it did in the original file.
 *
 * The src/legacy files stay the editable sources. Runs automatically via the
 * predev / prebuild npm hooks.
 */
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SRC_DIR = join(root, 'src', 'legacy');
const OUT = join(root, 'public', 'js', 'tncsc-engine.js');

// Numeric filename prefixes define the order; it is the original source order.
const files = readdirSync(SRC_DIR)
  .filter((f) => f.endsWith('.js'))
  .sort();

if (files.length === 0) throw new Error('no engine sources found in src/legacy');

const banner =
  '/* TNCSC CRS engine - generated by tools/bundle-engine.mjs. Do not edit.\n' +
  '   Sources: src/legacy/*.js (edit those instead).\n' +
  `   Parts: ${files.join(', ')} */\n`;

const body = files
  .map((f) => `\n/* ═══ ${f} ${'═'.repeat(Math.max(0, 60 - f.length))} */\n` + readFileSync(join(SRC_DIR, f), 'utf8'))
  .join('');

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, banner + body, 'utf8');
console.log(`bundled ${files.length} files -> public/js/tncsc-engine.js`);
